// Generate a repositories/<repo>.yaml config file from onboarding request fields.

import { resolveProfilesFor } from './lib/profile-map.mjs';

/**
 * @param {{ repoName: string, type: string, language: string, options: string[] }} request
 * @returns {string} YAML content for repositories/<repo>.yaml
 */
export function generateRepoConfig(request) {
    const { repoName, type, language, options } = request;

    if (!repoName) throw new Error('repoName is required');
    if (!type) throw new Error('type is required');
    if (!language) throw new Error('language is required');

    const profiles = resolveProfilesFor(language, type);

    const hasOption = (name) => options.some((o) => o.includes(name));

    return [
        `# Generated by golden-path onboarding`,
        `repository: ${repoName}`,
        ``,
        `profiles:`,
        ...profiles.map((p) => `  - ${p}`),
        ``,
        `options:`,
        `  codeql: ${hasOption('codeql')}`,
        `  gitleaks: ${hasOption('gitleaks')}`,
        `  dependabot: ${hasOption('dependabot')}`,
        `  releaseAutomation: ${hasOption('release') || hasOption('release automation')}`,
        ``,
    ].join('\n');
}
